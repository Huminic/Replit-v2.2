async function fetchOrg(orgId) {
  const r = await pool.query('SELECT id, name, partner_id FROM organizations WHERE id=$1', [orgId]);
  if (r.rows.length === 0) return null;
  const row = r.rows[0];
  return { id: row.id, name: row.name, partnerId: row.partner_id };
}

function sleep(ms) { return new Promise(res => setTimeout(res, ms)); }

async function sendCorrectionResend({ from, to, cc, bcc, subject, html }) {
  const res = await fetch('https://api.resend.com/emails', {
    method: 'POST',
    headers: {
      Authorization: `Bearer ${process.env.RESEND_API_KEY}`,
      'Content-Type': 'application/json',
    },
    body: JSON.stringify({ from, to, cc: cc?.length ? cc : undefined, bcc: bcc?.length ? bcc : undefined, subject, html }),
  });
  if (!res.ok) {
    const body = await res.text();
    return { sent: false, error: `Resend ${res.status}: ${body}` };
  }
  const data = await res.json();
  return { sent: true, messageId: data.id };
}

// Build sales-only lead id set for a store
function loadSalesIds(slug) {
  const path = `/tmp/sales-filter-2026-04-21/${slug}-sales-ids.json`;
  const arr = JSON.parse(readFileSync(path, 'utf-8'));
  return new Set(arr.map(String));
}

function loadRevisedHtml(slug) {
  return readFileSync(`/tmp/revised-reports-2026-04-21/${slug}.html`, 'utf-8');
}

